<?php

namespace Tests\Browser;

use App\Models\Agendamento;
use App\Models\User;
use Illuminate\Foundation\Testing\DatabaseMigrations;
use Illuminate\Foundation\Testing\DatabaseTruncation;
use Laravel\Dusk\Browser;
use Tests\DuskTestCase;

class AgendamentoCrudTest extends DuskTestCase
{
    use DataBaseTruncation;

    public function test_create_agendamento(): void
    {
        $model = new Agendamento;
        $divulgaOption = $model->divulgaOptions()[0] ?? 'Sim';
        $tipoOption = $model->tipoOptions()[0] ?? 'Mestrado';
        $docentes = $model->docentes();
        $orientadorCodpes = (string) ($docentes[0]['codpes'] ?? '');

        $this->assertNotEmpty($orientadorCodpes, 'Nenhum docente retornado pelo Replicado para selecionar no formulário.');

        $titulo = 'Análise de Otimização Aplicada a Sistemas Distribuídos';

        $this->browse(function (Browser $browser) use ($divulgaOption, $tipoOption, $orientadorCodpes, $titulo) {
            $this->loginSenhaUnica($browser, 111111);

            $browser->visit('/agendamentos/create')
                ->waitForText('Dados do trabalho acadêmico')
                ->type('outro_recomendado_', 'aluno.alternativo@gmail.com')
                ->select('divulgar_e_mail_', $divulgaOption)
                ->select('tipo', $tipoOption)
                ->type('titulo', $titulo)
                ->type('resumo', 'Resumo completo do trabalho acadêmico gerado pelo teste automatizado Dusk.')
                ->type('palavras_chave', 'Otimização, Sistemas, Laravel')
                ->type('titulo_ingles', 'Applied Optimization Analysis for Distributed Systems')
                ->type('keywords', 'Optimization, Systems, Laravel')
                ->type('abstract', 'Full abstract of the academic work generated by the automated Dusk test.')
                ->clear('data_da_defesa')
                ->type('data_da_defesa', '15/12/2026')
                ->keys('input[name="data_da_defesa"]', '{escape}')
                ->clear('horario')
                ->type('horario', '14:00')
                ->type('sala', 'Sala 104 - Prédio da Administração')
                ->select('numero_usp_do_orientador', $orientadorCodpes)
                ->press('Enviar')
                ->waitForText($titulo);

            $browser->clickLink('Sair')
                ->waitForText('Entrar');
        });

        $this->assertDatabaseHas('agendamentos', [
            'titulo'                   => $titulo,
            'sala'                     => 'Sala 104 - Prédio da Administração',
            'numero_usp_do_orientador' => $orientadorCodpes,
        ]);
    }
}
